//!
//! An indicator belongs here if its output answers "how much is price
//! moving?": true range, ATR, historical volatility, Bollinger/Keltner band
//! width, and similar. Output is in price units or a percentage of price.
//!
//! Not here: directional efficiency or trend-vs-chop scores (see `structure`),
//! smoothed price lines (see `filters`), or generic statistical quantities
