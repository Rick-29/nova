//! Backend builders.
//!
//! Each backend consumes the IR and owns everything framework-specific:
//! wrapper naming, generic instantiation, type conversion, error mapping,
//! attributes and documentation placement. Builders never parse source.
//!
//! Adding a backend means: a [`BackendKind`] variant, a builder implementing
//! [`BackendBuilder`], one line in [`factory`], a Cargo feature and tests.

pub mod factory;
pub mod napi;
pub mod python;
pub mod types;
pub mod uniffi;
pub mod wasm;
pub mod wrapper_fn;

use syn::{Ident, Path, Type};
use zyn::TokenStream;

use crate::ir::{BackendKind, BackendOption, ErrorData, IndicatorData, MethodData};

/// Additions a backend makes for the `#[bindings_error]` type.
#[derive(Default)]
pub struct ErrorGlue {
    /// Attributes placed on the error item itself.
    pub attrs: TokenStream,
    /// Items emitted after the error item.
    pub items: TokenStream,
}

pub trait BackendBuilder: Sync {
    fn kind(&self) -> BackendKind;

    /// Cargo feature that gates every item this backend generates.
    fn feature(&self) -> &'static str;

    /// Rust name of the wrapper type for `data`.
    fn wrapper_ident(&self, data: &IndicatorData) -> Ident;

    /// Concrete type used for the indicator's numeric type parameters.
    fn numeric_type(&self) -> Type {
        syn::parse_quote!(f64)
    }

    /// Checks the struct-level options given to this backend.
    fn validate_options(&self, options: &[BackendOption]) -> syn::Result<()>;

    /// Checks that a method can be exported by this backend.
    fn validate_method(&self, data: &IndicatorData, method: &MethodData) -> syn::Result<()>;

    /// The wrapper type, generated by the derive.
    fn build_struct(&self, data: &IndicatorData) -> syn::Result<TokenStream>;

    /// One complete impl block for `wrapper` with bindings for `methods`.
    fn build_methods(
        &self,
        data: &IndicatorData,
        wrapper: &Path,
        methods: &[&MethodData],
    ) -> syn::Result<TokenStream>;

    /// Checks the options given to this backend in `#[bindings_error(...)]`.
    fn validate_error_options(&self, options: &[BackendOption]) -> syn::Result<()>;

    /// Error conversion glue for the type annotated with `#[bindings_error]`.
    fn build_error(&self, error: &ErrorData) -> syn::Result<ErrorGlue>;
}

/// Rejects every option: for backends that take none yet.
pub fn no_options(kind: BackendKind, options: &[BackendOption]) -> syn::Result<()> {
    match options.first() {
        Some(option) => Err(syn::Error::new(
            option.key.span(),
            format!("backend `{}` takes no options", kind.name()),
        )),
        None => Ok(()),
    }
}

/// For backends that report errors through `Display`: a compile-time check
/// that the error type implements it.
pub fn display_check(feature: &str, error: &Ident) -> ErrorGlue {
    ErrorGlue {
        attrs: TokenStream::new(),
        items: template! {
            #[cfg(feature = {{ feature }})]
            const _: fn() = || {
                fn __nova_bindings_assert_display<T: ::core::fmt::Display>() {}
                __nova_bindings_assert_display::<{{ error }}>();
            };
        },
    }
}

/// Doc attributes copied onto generated items.
pub fn doc_attrs(docs: &crate::ir::Docs) -> TokenStream {
    let attrs = &docs.raw_attributes;
    template! { @for (attr in attrs.iter()) { {{ attr }} } }
}
